function t(key, lang) {
  const l = lang || getCurrentLang();
  return I18N[l]?.[key] ?? I18N.en[key] ?? key;
}

function getCurrentLang() {
  return localStorage.getItem('portfolio-lang') || 'en';
}

function applyLanguage(lang) {
  if (!I18N[lang]) lang = 'en';

  document.body.classList.remove('lang-pt', 'lang-es');
  if (lang === 'pt') document.body.classList.add('lang-pt');
  if (lang === 'es') document.body.classList.add('lang-es');

  document.documentElement.lang = lang;
  localStorage.setItem('portfolio-lang', lang);

  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.dataset.i18n;
    const value = t(key, lang);
    if (el.dataset.i18nHtml === 'true') el.innerHTML = value;
    else el.textContent = value;
  });

  document.querySelectorAll('.lang-switch__btn').forEach(btn => {
    btn.classList.toggle('active', btn.dataset.setLang === lang);
  });

  const textarea = document.getElementById('message');
  if (textarea) textarea.placeholder = t('form.placeholder', lang);

  const selectOpts = {
    fire: 'form.opt.fire',
    plumb: 'form.opt.plumb',
    elec: 'form.opt.elec',
    struct: 'form.opt.struct',
    mep: 'form.opt.mep',
    other: 'form.opt.other'
  };
  document.querySelectorAll('#project_type option[value]').forEach(opt => {
    const key = selectOpts[opt.value];
    if (key) opt.textContent = t(key, lang);
  });
}
